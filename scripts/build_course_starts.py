def _s2c_fields(key):
    """スタート→初角の数値と status/level。禁止5: 欠損を0にせず NULL+status。"""
    v = S2C.get(key)
    if v is None:
        return None, CHECK, None          # 資料に行が無い（障害距離など）
    if v == CHECK:
        return None, CHECK, None
    if v == MERGE_AMB:
        return None, MERGE_AMB, None      # 禁止2: 本線合流距離を初角距離にしない
    if v == NO_CORNER:
        return None, NO_CORNER, None      # 欠損ではなく「存在しない」
    return float(v[0]), 'ok', v[1]


